CREATE TABLE teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_team_id BIGINT,
    name VARCHAR(150) NOT NULL,
    code VARCHAR(20),
    country VARCHAR(100),
    logo_url VARCHAR(500),
    data_source VARCHAR(20) NOT NULL,
    synthetic BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_teams_provider_source UNIQUE (provider_team_id, data_source),
    CONSTRAINT ck_teams_data_source CHECK (data_source IN ('MOCK', 'LIVE')),
    CONSTRAINT ck_teams_synthetic_source CHECK (NOT synthetic OR data_source = 'MOCK')
);

CREATE TABLE competitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_competition_id BIGINT,
    name VARCHAR(150) NOT NULL,
    country VARCHAR(100),
    logo_url VARCHAR(500),
    data_source VARCHAR(20) NOT NULL,
    synthetic BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_competitions_provider_source UNIQUE (provider_competition_id, data_source),
    CONSTRAINT ck_competitions_data_source CHECK (data_source IN ('MOCK', 'LIVE')),
    CONSTRAINT ck_competitions_synthetic_source CHECK (NOT synthetic OR data_source = 'MOCK')
);

CREATE TABLE matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_fixture_id BIGINT,
    competition_id BIGINT NOT NULL,
    season INTEGER,
    round VARCHAR(100),
    kickoff_time TIMESTAMPTZ NOT NULL,
    venue_name VARCHAR(200),
    home_team_id BIGINT NOT NULL,
    away_team_id BIGINT NOT NULL,
    home_goals INTEGER,
    away_goals INTEGER,
    status VARCHAR(30) NOT NULL,
    result VARCHAR(100),
    data_source VARCHAR(20) NOT NULL,
    synthetic BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_matches_provider_source UNIQUE (provider_fixture_id, data_source),
    CONSTRAINT fk_matches_competition FOREIGN KEY (competition_id) REFERENCES competitions (id) ON DELETE RESTRICT,
    CONSTRAINT fk_matches_home_team FOREIGN KEY (home_team_id) REFERENCES teams (id) ON DELETE RESTRICT,
    CONSTRAINT fk_matches_away_team FOREIGN KEY (away_team_id) REFERENCES teams (id) ON DELETE RESTRICT,
    CONSTRAINT ck_matches_distinct_teams CHECK (home_team_id <> away_team_id),
    CONSTRAINT ck_matches_home_goals CHECK (home_goals IS NULL OR home_goals >= 0),
    CONSTRAINT ck_matches_away_goals CHECK (away_goals IS NULL OR away_goals >= 0),
    CONSTRAINT ck_matches_season CHECK (season IS NULL OR season BETWEEN 1888 AND 9999),
    CONSTRAINT ck_matches_data_source CHECK (data_source IN ('MOCK', 'LIVE')),
    CONSTRAINT ck_matches_synthetic_source CHECK (NOT synthetic OR data_source = 'MOCK')
);

CREATE INDEX idx_teams_name ON teams (name);
CREATE INDEX idx_competitions_name ON competitions (name);
CREATE INDEX idx_matches_kickoff_time ON matches (kickoff_time DESC);
CREATE INDEX idx_matches_home_team_kickoff ON matches (home_team_id, kickoff_time DESC);
CREATE INDEX idx_matches_away_team_kickoff ON matches (away_team_id, kickoff_time DESC);
CREATE INDEX idx_matches_competition_season ON matches (competition_id, season);
CREATE INDEX idx_matches_status_kickoff ON matches (status, kickoff_time DESC);
