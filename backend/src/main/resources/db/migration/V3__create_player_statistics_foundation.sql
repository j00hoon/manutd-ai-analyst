CREATE TABLE players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_player_id BIGINT NOT NULL,
    name VARCHAR(200) NOT NULL,
    photo_url VARCHAR(500),
    data_source VARCHAR(20) NOT NULL,
    synthetic BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_players_provider_source UNIQUE (provider_player_id, data_source),
    CONSTRAINT ck_players_data_source CHECK (data_source IN ('MOCK', 'LIVE')),
    CONSTRAINT ck_players_synthetic_source CHECK (NOT synthetic OR data_source = 'MOCK')
);

CREATE TABLE player_match_statistics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL,
    player_id BIGINT NOT NULL,
    team_id BIGINT NOT NULL,
    minutes INTEGER,
    position VARCHAR(30),
    jersey_number INTEGER,
    rating NUMERIC(4, 2),
    captain BOOLEAN,
    substitute BOOLEAN,
    offsides INTEGER,
    shots_total INTEGER,
    shots_on_target INTEGER,
    goals INTEGER,
    assists INTEGER,
    saves INTEGER,
    passes_total INTEGER,
    key_passes INTEGER,
    pass_accuracy_percentage NUMERIC(5, 2),
    tackles_total INTEGER,
    blocks INTEGER,
    interceptions INTEGER,
    duels_total INTEGER,
    duels_won INTEGER,
    dribbles_attempted INTEGER,
    dribbles_succeeded INTEGER,
    fouls_drawn INTEGER,
    fouls_committed INTEGER,
    yellow_cards INTEGER,
    red_cards INTEGER,
    penalties_won INTEGER,
    penalties_committed INTEGER,
    penalties_scored INTEGER,
    penalties_missed INTEGER,
    penalties_saved INTEGER,
    coverage_status VARCHAR(20) NOT NULL,
    data_source VARCHAR(20) NOT NULL,
    synthetic BOOLEAN NOT NULL DEFAULT FALSE,
    provider_checked_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_player_match_statistics_match_player UNIQUE (match_id, player_id),
    CONSTRAINT fk_player_match_statistics_match FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE,
    CONSTRAINT fk_player_match_statistics_player FOREIGN KEY (player_id) REFERENCES players (id) ON DELETE RESTRICT,
    CONSTRAINT fk_player_match_statistics_team FOREIGN KEY (team_id) REFERENCES teams (id) ON DELETE RESTRICT,
    CONSTRAINT ck_player_match_statistics_minutes CHECK (minutes IS NULL OR minutes BETWEEN 0 AND 130),
    CONSTRAINT ck_player_match_statistics_jersey CHECK (jersey_number IS NULL OR jersey_number BETWEEN 0 AND 999),
    CONSTRAINT ck_player_match_statistics_rating CHECK (rating IS NULL OR rating BETWEEN 0 AND 10),
    CONSTRAINT ck_player_match_statistics_pass_accuracy CHECK (pass_accuracy_percentage IS NULL OR pass_accuracy_percentage BETWEEN 0 AND 100),
    CONSTRAINT ck_player_match_statistics_nonnegative CHECK (
        (offsides IS NULL OR offsides >= 0) AND
        (shots_total IS NULL OR shots_total >= 0) AND
        (shots_on_target IS NULL OR shots_on_target >= 0) AND
        (goals IS NULL OR goals >= 0) AND
        (assists IS NULL OR assists >= 0) AND
        (saves IS NULL OR saves >= 0) AND
        (passes_total IS NULL OR passes_total >= 0) AND
        (key_passes IS NULL OR key_passes >= 0) AND
        (tackles_total IS NULL OR tackles_total >= 0) AND
        (blocks IS NULL OR blocks >= 0) AND
        (interceptions IS NULL OR interceptions >= 0) AND
        (duels_total IS NULL OR duels_total >= 0) AND
        (duels_won IS NULL OR duels_won >= 0) AND
        (dribbles_attempted IS NULL OR dribbles_attempted >= 0) AND
        (dribbles_succeeded IS NULL OR dribbles_succeeded >= 0) AND
        (fouls_drawn IS NULL OR fouls_drawn >= 0) AND
        (fouls_committed IS NULL OR fouls_committed >= 0) AND
        (yellow_cards IS NULL OR yellow_cards >= 0) AND
        (red_cards IS NULL OR red_cards >= 0) AND
        (penalties_won IS NULL OR penalties_won >= 0) AND
        (penalties_committed IS NULL OR penalties_committed >= 0) AND
        (penalties_scored IS NULL OR penalties_scored >= 0) AND
        (penalties_missed IS NULL OR penalties_missed >= 0) AND
        (penalties_saved IS NULL OR penalties_saved >= 0)
    ),
    CONSTRAINT ck_player_match_statistics_coverage CHECK (coverage_status IN ('COMPLETE', 'PARTIAL', 'UNAVAILABLE', 'NOT_SYNCED')),
    CONSTRAINT ck_player_match_statistics_data_source CHECK (data_source IN ('MOCK', 'LIVE')),
    CONSTRAINT ck_player_match_statistics_synthetic_source CHECK (NOT synthetic OR data_source = 'MOCK')
);

CREATE TABLE match_player_statistics_coverage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL,
    coverage_status VARCHAR(20) NOT NULL,
    valid_player_count INTEGER NOT NULL,
    skipped_player_count INTEGER NOT NULL,
    data_source VARCHAR(20) NOT NULL,
    synthetic BOOLEAN NOT NULL DEFAULT FALSE,
    provider_checked_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_match_player_statistics_coverage_match UNIQUE (match_id),
    CONSTRAINT fk_match_player_statistics_coverage_match FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE,
    CONSTRAINT ck_match_player_statistics_coverage_counts CHECK (valid_player_count >= 0 AND skipped_player_count >= 0),
    CONSTRAINT ck_match_player_statistics_coverage_status CHECK (coverage_status IN ('COMPLETE', 'PARTIAL', 'UNAVAILABLE')),
    CONSTRAINT ck_match_player_statistics_coverage_source CHECK (data_source IN ('MOCK', 'LIVE')),
    CONSTRAINT ck_match_player_statistics_coverage_synthetic_source CHECK (NOT synthetic OR data_source = 'MOCK')
);

CREATE INDEX idx_player_match_statistics_team_match ON player_match_statistics (team_id, match_id);
CREATE INDEX idx_player_match_statistics_player_match ON player_match_statistics (player_id, match_id);
CREATE INDEX idx_player_match_statistics_source_coverage ON player_match_statistics (data_source, coverage_status);
CREATE INDEX idx_match_player_statistics_coverage_source ON match_player_statistics_coverage (data_source, coverage_status);
