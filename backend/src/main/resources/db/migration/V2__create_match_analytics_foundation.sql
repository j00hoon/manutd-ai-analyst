ALTER TABLE matches
    ADD COLUMN home_penalty_goals INTEGER,
    ADD COLUMN away_penalty_goals INTEGER,
    ADD CONSTRAINT ck_matches_home_penalty_goals
        CHECK (home_penalty_goals IS NULL OR home_penalty_goals >= 0),
    ADD CONSTRAINT ck_matches_away_penalty_goals
        CHECK (away_penalty_goals IS NULL OR away_penalty_goals >= 0);

CREATE TABLE team_match_statistics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL,
    team_id BIGINT NOT NULL,
    shots INTEGER,
    shots_on_target INTEGER,
    possession_percentage NUMERIC(5, 2),
    coverage_status VARCHAR(20) NOT NULL,
    data_source VARCHAR(20) NOT NULL,
    synthetic BOOLEAN NOT NULL DEFAULT FALSE,
    provider_checked_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_team_match_statistics_match_team UNIQUE (match_id, team_id),
    CONSTRAINT fk_team_match_statistics_match
        FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE,
    CONSTRAINT fk_team_match_statistics_team
        FOREIGN KEY (team_id) REFERENCES teams (id) ON DELETE RESTRICT,
    CONSTRAINT ck_team_match_statistics_shots
        CHECK (shots IS NULL OR shots >= 0),
    CONSTRAINT ck_team_match_statistics_shots_on_target
        CHECK (shots_on_target IS NULL OR shots_on_target >= 0),
    CONSTRAINT ck_team_match_statistics_possession
        CHECK (possession_percentage IS NULL OR possession_percentage BETWEEN 0 AND 100),
    CONSTRAINT ck_team_match_statistics_coverage
        CHECK (coverage_status IN ('COMPLETE', 'PARTIAL', 'UNAVAILABLE', 'NOT_SYNCED')),
    CONSTRAINT ck_team_match_statistics_data_source
        CHECK (data_source IN ('MOCK', 'LIVE')),
    CONSTRAINT ck_team_match_statistics_synthetic_source
        CHECK (NOT synthetic OR data_source = 'MOCK')
);

CREATE INDEX idx_team_match_statistics_team_match
    ON team_match_statistics (team_id, match_id);
CREATE INDEX idx_team_match_statistics_source_coverage
    ON team_match_statistics (data_source, coverage_status);
